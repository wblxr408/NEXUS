#!/usr/bin/env python3
"""Generate a continuous, textured monocular sequence for ORB-SLAM2.

The scene is deliberately deterministic and metric: fixed 3-D landmarks are
projected from a smooth camera trajectory.  ``ground_truth/`` is evaluator
only; ORB-SLAM2 receives only ``rgb.txt`` and images.
"""
from __future__ import annotations

import argparse
import csv
import json
import math
from pathlib import Path

import cv2
import numpy as np


def look_at(position: np.ndarray, target: np.ndarray) -> np.ndarray:
    f = target - position
    f /= np.linalg.norm(f)
    r = np.cross(f, np.array([0.0, 0.0, 1.0]))
    r /= np.linalg.norm(r)
    d = np.cross(f, r)
    return np.vstack((r, d, f))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="data/processed/nexus_sandbox_orb_slam2_mono_v01")
    ap.add_argument("--frames", type=int, default=240)
    ap.add_argument("--fps", type=float, default=10.0)
    ap.add_argument("--seed", type=int, default=20260827)
    ap.add_argument("--post-init-speed", type=float, default=0.0, help="post-initialization x drift in m/s")
    args = ap.parse_args()
    out = Path(args.out); rgb = out / "rgb"; truth = out / "ground_truth"
    rgb.mkdir(parents=True, exist_ok=True); truth.mkdir(parents=True, exist_ok=True)
    w, h, fx, fy, cx, cy = 640, 480, 535.0, 535.0, 319.5, 239.5
    rng = np.random.default_rng(args.seed)
    # Ground and elevated points provide both texture and monocular parallax.
    points = np.column_stack((rng.uniform(0.15, 3.85, 700),
                              rng.uniform(0.15, 4.55, 700),
                              rng.uniform(0.00, 1.65, 700)))
    # Add a regular set of high-contrast landmarks, making feature density
    # stable across views rather than dependent on random coincidences.
    grid = np.array([(x, y, z) for z in (0.03, 0.35, 0.8, 1.3)
                     for x in np.linspace(0.2, 3.8, 15)
                     for y in np.linspace(0.2, 4.5, 18)], dtype=float)
    points = np.vstack((points, grid))
    colors = rng.integers(30, 240, size=(len(points), 3), dtype=np.uint8)
    patterns = rng.integers(0, 2, size=(len(points), 9, 9), dtype=np.uint8)
    base_ns = 1_777_000_000_000_000_000
    rows = []
    gt_rows = []
    for i in range(args.frames):
        t = i / args.fps
        # Smooth figure-eight motion, with small height and yaw changes.
        motion_t = min(t, 3.0)
        p = np.array([2.0 + 0.72 * math.sin(0.9 * motion_t),
                      2.35 + 0.85 * math.sin(0.55 * motion_t + 0.4),
                      2.75 + 0.12 * math.sin(0.17 * motion_t)])
        if t > 3.0:
            # Hold station after initialization for the first compatibility
            # run; this isolates map/pose execution from local-BA failures.
            p += np.array([args.post_init_speed * (t - 3.0), 0.0, 0.0])
        target = np.array([2.0 + 0.15 * math.sin(0.09 * motion_t),
                           2.35, 0.25])
        R = look_at(p, target)
        pc = (R @ (points - p).T).T
        ok = pc[:, 2] > 0.15
        uv = pc @ np.array([[fx, 0, cx], [0, fy, cy], [0, 0, 1]], dtype=float).T
        uv = uv[:, :2] / uv[:, 2:3]
        image = np.full((h, w, 3), (122, 148, 164), dtype=np.uint8)
        visible = np.where(ok & (uv[:, 0] >= 6) & (uv[:, 0] < w - 6) &
                           (uv[:, 1] >= 6) & (uv[:, 1] < h - 6))[0]
        # Draw far points first. Cross/checker patches produce repeatable ORB
        # corners while retaining point identity over time.
        for j in visible[np.argsort(pc[visible, 2])[::-1]]:
            x, y = np.rint(uv[j]).astype(int); c = tuple(int(v) for v in colors[j])
            cv2.rectangle(image, (x - 5, y - 5), (x + 5, y + 5), c, -1)
            # Per-landmark binary micro-texture gives descriptors identity
            # across frames (a single generic cross is too repetitive).
            for py in range(9):
                for px in range(9):
                    if patterns[j, py, px]:
                        image[y - 4 + py, x - 4 + px] = (20, 20, 20)
            if int(colors[j, 0]) % 3 == 0:
                cv2.line(image, (x - 4, y), (x + 4, y), (20, 20, 20), 1)
                cv2.line(image, (x, y - 4), (x, y + 4), (20, 20, 20), 1)
            elif int(colors[j, 0]) % 3 == 1:
                cv2.line(image, (x - 4, y - 4), (x + 4, y + 4), (20, 20, 20), 1)
            else:
                cv2.circle(image, (x, y), 2, (20, 20, 20), 1)
        name = f"{i:06d}.png"; cv2.imwrite(str(rgb / name), image)
        ts = base_ns + int(round(i * 1e9 / args.fps)); rows.append((ts / 1e9, f"rgb/{name}"))
        gt_rows.append((i, ts, *p, *R.reshape(-1)))
    with (out / "rgb.txt").open("w", encoding="utf-8") as f:
        # The upstream mono_tum loader unconditionally skips three header lines.
        f.write("# generated by generate_orb_slam2_dataset.py\n# timestamp filename\n#\n")
        f.writelines(f"{t:.9f} {name}\n" for t, name in rows)
    with (truth / "camera_pose_map.csv").open("w", newline="", encoding="utf-8") as f:
        fields = ["sequence", "sample_timestamp_ns", "camera_x_m", "camera_y_m", "camera_z_m"] + [f"R_map_camera_{r}{c}" for r in range(3) for c in range(3)]
        wri = csv.writer(f); wri.writerow(fields); wri.writerows(gt_rows)
    anchors = [("anchor_0", np.array([0.15, 0.15, 0.40])), ("anchor_1", np.array([3.85, 0.15, 2.40])),
               ("anchor_2", np.array([3.85, 4.55, 4.40])), ("anchor_3", np.array([0.15, 4.55, 1.40]))]
    with (truth / "platform_pose.csv").open("w", newline="", encoding="utf-8") as pf, \
         (out / "platform_attitude.csv").open("w", newline="", encoding="utf-8") as af, \
         (out / "trajectory.csv").open("w", newline="", encoding="utf-8") as rf:
        pw = csv.writer(pf); aw = csv.writer(af); rw = csv.writer(rf)
        pw.writerow(["sequence", "sample_timestamp_ns", "base_x_m", "base_y_m", "base_z_m", "frame_id"])
        aw.writerow(["sequence", "sample_timestamp_ns", *[f"base_R_map_{r}{c}" for r in range(3) for c in range(3)], "frame_id"])
        rw.writerow(["sequence", "sample_timestamp_ns", "uwb_anchor_id", "uwb_range_m", "range_valid", "frame_id"])
        for sequence, timestamp, x, y, z, *flat_R in gt_rows:
            p = np.array([x, y, z]); pw.writerow([sequence, timestamp, x, y, z, "base_link"])
            aw.writerow([sequence, timestamp, *flat_R, "base_link"])
            for anchor_id, anchor in anchors:
                rw.writerow([sequence, timestamp, anchor_id, np.linalg.norm(p-anchor) + rng.normal(0.0, 0.015), 1, "base_link"])
    (out / "camera.yaml").write_text("""%YAML:1.0\nCamera.fx: 535.0\nCamera.fy: 535.0\nCamera.cx: 319.5\nCamera.cy: 239.5\nCamera.k1: 0.0\nCamera.k2: 0.0\nCamera.p1: 0.0\nCamera.p2: 0.0\nCamera.k3: 0.0\nCamera.fps: 10.0\nCamera.RGB: 0\nORBextractor.nFeatures: 1800\nORBextractor.scaleFactor: 1.2\nORBextractor.nLevels: 8\nORBextractor.iniThFAST: 12\nORBextractor.minThFAST: 5\nViewer.KeyFrameSize: 0.05\nViewer.KeyFrameLineWidth: 1\nViewer.GraphLineWidth: 0.9\nViewer.PointSize: 2\nViewer.CameraSize: 0.08\nViewer.CameraLineWidth: 3\nViewer.ViewpointX: 0\nViewer.ViewpointY: -0.7\nViewer.ViewpointZ: -1.8\nViewer.ViewpointF: 500\n""", encoding="utf-8")
    metadata = {"dataset_id": "nexus_sandbox_orb_slam2_mono_v01", "frames": args.frames, "fps": args.fps, "image_size": [w, h], "coordinate_frame": "map", "unit": "m", "truth_not_visible_to_algorithm": True}
    (out / "metadata.json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
